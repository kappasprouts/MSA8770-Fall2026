"use client";

import { useEffect, useState } from "react";
import type { ExceptionRecord } from "@/lib/exception-types";
import { exceptionPriorityTone, exceptionSourceLabel, exceptionStatusLabel, formatExceptionDate } from "@/lib/exception-display";
import { requestJson } from "@/lib/http";
import RequestState from "./RequestState";
import WorkspaceIcon from "./WorkspaceIcon";
import ItCaseActions from "./ItCaseActions";
import styles from "./eaos.module.css";
import details from "./exceptions.module.css";

export default function ApplicantExceptionDetails({ exceptionId, onBack, onOpenApplicant }: {
  exceptionId: string;
  onBack: () => void;
  onOpenApplicant: (appId: string) => void;
}) {
  const [record, setRecord] = useState<ExceptionRecord | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [attempt, setAttempt] = useState(0);

  useEffect(() => {
    const controller = new AbortController();
    requestJson<{ record: ExceptionRecord }>(`/api/exceptions/${encodeURIComponent(exceptionId)}`, { signal: controller.signal })
      .then(body => {
        if (controller.signal.aborted) return;
        const selected = body.record;
        if (!selected) throw new Error(`Exception "${exceptionId}" could not be found. It may no longer need technical review.`);
        setRecord(selected);
      })
      .catch(reason => {
        if (!controller.signal.aborted) setError(reason instanceof Error ? reason.message : "Could not load this exception.");
      })
      .finally(() => { if (!controller.signal.aborted) setLoading(false); });
    return () => controller.abort();
  }, [exceptionId, attempt]);

  function retry() {
    setRecord(null);
    setLoading(true);
    setError("");
    setAttempt(value => value + 1);
  }

  return (
    <>
      <button type="button" onClick={onBack} className={`${styles.secondaryButton} ${details.backLink}`}>
        <WorkspaceIcon name="back" /> Back to Error Queue
      </button>

      {loading ? <RequestState kind="loading" title="Loading exception details…" description="Retrieving the findings and audit history." />
        : error || !record ? <RequestState kind="error" title="Exception details unavailable" description={error || "The selected exception could not be loaded."} onRetry={retry} />
        : <>
          <section className={styles.card} aria-labelledby="exception-heading">
            <div className={details.cardHeader}>
              <div>
                <p className={styles.eyebrow}>Technical exception record</p>
                <h2 id="exception-heading" className={details.identity}>{record.applicantId ?? "Unmatched record"} · {record.applicantName}</h2>
              </div>
              <span className={`${styles.pill} ${styles[exceptionPriorityTone(record.severity)]}`}>{exceptionStatusLabel(record.severity)} priority</span>
            </div>
            <p className={styles.help}>{record.intendedMajor ?? "Intended major unavailable"}</p>
          </section>

          <div className={details.detailsGrid}>
            <div>
              <section className={styles.card}>
                <div className={details.cardHeader}>
                  <div><p className={styles.eyebrow}>Exception category</p><h2>{record.category}</h2></div>
                  <span className={styles.pill}>{exceptionStatusLabel(record.status)}</span>
                </div>
                <div className={details.reason}>
                  <h3>Why the record was routed</h3>
                  <p>{record.summary}</p>
                </div>
              </section>

              <section className={styles.card}>
                <h2>Validation findings</h2>
                <p className={styles.help}>Findings generated by the component that stopped processing.</p>
                {record.findings.length ? <ol className={details.findings}>
                  {record.findings.map((finding, index) => <li key={`${finding}-${index}`}>{finding}</li>)}
                </ol> : <p className={styles.help}>No detailed validation findings were provided.</p>}
              </section>

              <section className={styles.card}>
                <h2>Affected documents</h2>
                <p className={styles.help}>Documents associated with this exception.</p>
                {record.affectedDocuments.length ? <ul className={details.documents}>
                  {record.affectedDocuments.map(document => <li key={document}>{document}</li>)}
                </ul> : <p className={styles.help}>No specific document was associated with this exception.</p>}
              </section>

              <section className={styles.card}>
                <h2>Audit history</h2>
                <p className={styles.help}>Recent events recorded for this exception.</p>
                {record.auditHistory.length ? <ol className={details.audit}>
                  {record.auditHistory.map((event, index) => <li key={`${event.action}-${event.createdAt}-${index}`}>
                    <strong>{exceptionStatusLabel(event.action)}</strong>
                    <p className={styles.muted}>{event.actor} · {formatExceptionDate(event.createdAt)}</p>
                  </li>)}
                </ol> : <p className={styles.help}>No audit events are available.</p>}
              </section>
            </div>

            <aside aria-label="Exception summary and follow-up">
              <section className={styles.card}>
                <h2>Exception summary</h2>
                <dl className={details.facts}>
                  {[
                    ["Applicant", record.applicantId ?? "Unmatched record"],
                    ["Applicant name", record.applicantName || "Not provided"],
                    ["Workflow status", exceptionStatusLabel(record.status)],
                    ["Detected by", exceptionSourceLabel(record.source)],
                    ["Priority", exceptionStatusLabel(record.severity)],
                    ["Last event", formatExceptionDate(record.updatedAt)],
                    ["Follow-up owner", record.owner || "Unassigned"],
                  ].map(([label, value]) => <div key={label}><dt>{label}</dt><dd>{value}</dd></div>)}
                </dl>
              </section>

              <section className={`${styles.card} ${details.guidance}`}>
                <h2>Recommended technical action</h2>
                <p>Review the validation findings and affected documents. Correct the underlying source, matching, or model-output problem before rerunning the affected workflow step.</p>
              </section>

              {record.hasDossier && record.applicantId && <button type="button" onClick={() => { if (record.applicantId) onOpenApplicant(record.applicantId); }} className={`${styles.button} ${details.openDossier}`}>
                Open available applicant dossier
              </button>}

              <ItCaseActions key={`${record.caseId || record.id}-${record.revision ?? 0}`} record={record} onRefresh={retry} />
            </aside>
          </div>
        </>}
    </>
  );
}
